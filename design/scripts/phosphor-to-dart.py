"""Builds the app's Phosphor icon set from the vendored web fonts (MIT, prototype/vendor/phosphor).

Why: the phosphor_flutter package (2.1.0, last release 2024) no longer compiles on current Flutter
(IconData became a final class). We ship the same icons as two small font files and a Dart class with
the same call style: PhosphorIcons.house(PhosphorIconsStyle.fill).

It scans apps/mobile/lib for the icons in use, subsets the fonts to just those glyphs and writes
apps/mobile/lib/widgets/phosphor.g.dart. Re-run after using a new icon:
    python design/scripts/phosphor-to-dart.py
"""
import pathlib, re
from fontTools import subset
from fontTools.ttLib import TTFont

root = pathlib.Path(__file__).resolve().parents[2]
lib = root / "apps/mobile/lib"
src = root / "prototype/vendor/phosphor"
out_fonts = root / "apps/mobile/assets/fonts"

used = set()
for f in lib.rglob("*.dart"):
    if f.name == "phosphor.g.dart":
        continue
    used |= set(re.findall(r"PhosphorIcons\.(\w+)\(", f.read_text(encoding="utf-8")))

def kebab(n): return re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", n).lower()

def codes(css, prefix):
    return {m[0]: int(m[1], 16) for m in re.findall(prefix + r'\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"[^0-9a-f"]([0-9a-f]+)"', css)}

reg = codes((src / "regular/style.css").read_text(encoding="utf-8"), r"\.ph")
fil = codes((src / "fill/style.css").read_text(encoding="utf-8"), r"\.ph-fill")

missing = sorted(n for n in used if kebab(n) not in reg or kebab(n) not in fil)
if missing:
    raise SystemExit(f"Not in the Phosphor fonts: {missing}")

for style, file, table in (("Regular", "regular/Phosphor.woff2", reg), ("Fill", "fill/Phosphor-Fill.woff2", fil)):
    font = TTFont(src / file)
    font.flavor = None
    opts = subset.Options()
    opts.layout_features = []
    opts.notdef_outline = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=[table[kebab(n)] for n in used])
    s.subset(font)
    font.save(out_fonts / f"Phosphor-{style}.ttf")

lines = [
    "// GENERATED by design/scripts/phosphor-to-dart.py. Do not edit by hand.",
    "// Phosphor Icons (MIT, https://phosphoricons.com), see assets/fonts/PHOSPHOR_LICENSE.",
    "import 'package:flutter/widgets.dart';",
    "",
    "/// Bold is not bundled; it falls back to the filled glyph.",
    "enum PhosphorIconsStyle { regular, fill, bold }",
    "",
    "abstract final class PhosphorIcons {",
]
for n in sorted(used):
    k = kebab(n)
    lines.append(
        f"  static IconData {n}([PhosphorIconsStyle s = PhosphorIconsStyle.regular]) => s == PhosphorIconsStyle.regular"
        f" ? const IconData(0x{reg[k]:x}, fontFamily: 'PhosphorRegular') : const IconData(0x{fil[k]:x}, fontFamily: 'PhosphorFill');"
    )
lines += ["}", ""]
(lib / "widgets/phosphor.g.dart").write_text("\n".join(lines), encoding="utf-8")
print(f"{len(used)} icons ->", lib / "widgets/phosphor.g.dart")
