// Makes the Android launcher icons from the owner's real mark, brand/favicon.svg (never redrawn, D-065).
// - Old phones (Android 7 and below): the file as it is, resized.
// - Android 8+ (adaptive icon): the same file without its navy square, as the foreground, on a navy
//   background colour taken from the file (#0b1f44). The phone cuts the shape (circle, squircle…).
// Usage (from the repo root): node design/scripts/make-app-icon.mjs
// Needs Playwright's Chromium (pre-installed in cloud sessions; on the laptop: npx playwright install chromium).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const root = new URL("../../", import.meta.url);
const svg = readFileSync(new URL("brand/favicon.svg", root), "utf8");
const res = new URL("apps/mobile/android/app/src/main/res/", root);

// The navy square is the file's first <rect>; its colour becomes the adaptive background.
const rect = svg.match(/<rect\b[^>]*\/>/)?.[0];
const navy = rect?.match(/fill="(#[0-9a-fA-F]{6})"/)?.[1];
if (!rect || !navy) throw new Error("brand/favicon.svg changed shape: expected a <rect … fill=\"#xxxxxx\"/> background");
const inner = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(rect, "");

// Adaptive icons: 108 dp canvas, only a 66 dp circle in the middle is always visible. The mark's farthest point
// from its centre (256.5, 264) is ~236 units (the round end at bottom left), so scale it to fit that circle.
const safeRadius = (33 / 108) * 512;
const scale = (safeRadius / 236).toFixed(4);
const foreground = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><g transform="translate(256 256) scale(${scale}) translate(-256.5 -264)">${inner}</g></svg>`;

const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const browser = await chromium.launch();
const page = await browser.newPage();
async function render(markup, px, out) {
  await page.setViewportSize({ width: px, height: px });
  await page.setContent(
    `<html><body style="margin:0;background:transparent">${markup.replace("<svg ", `<svg width="${px}" height="${px}" `)}</body></html>`,
  );
  const png = await page.locator("svg").screenshot({ omitBackground: true });
  writeFileSync(out, png);
}
for (const [d, k] of Object.entries(densities)) {
  const dir = new URL(`mipmap-${d}/`, res);
  mkdirSync(dir, { recursive: true });
  await render(svg, Math.round(48 * k), new URL("ic_launcher.png", dir));
  await render(foreground, Math.round(108 * k), new URL("ic_launcher_foreground.png", dir));
}
await browser.close();

mkdirSync(new URL("mipmap-anydpi-v26/", res), { recursive: true });
writeFileSync(
  new URL("mipmap-anydpi-v26/ic_launcher.xml", res),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from brand/favicon.svg by design/scripts/make-app-icon.mjs (D-065). Do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`,
);
writeFileSync(
  new URL("values/ic_launcher_background.xml", res),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- The navy square of brand/favicon.svg (D-065). Generated by design/scripts/make-app-icon.mjs. -->
<resources>
    <color name="ic_launcher_background">${navy.toUpperCase()}</color>
</resources>
`,
);
console.log(`Icons made from brand/favicon.svg (background ${navy}, mark scale ${scale}).`);
